import assert from 'node:assert/strict';
import test from 'node:test';
import { Client, type Pool } from 'pg';
import dotenv from 'dotenv';
import { SessionQuestionStore } from './session-question-store';

test('PostgreSQL session questions stream numbered arrivals without approval and preserve hiding and anonymity', { skip: process.env.TEST_SESSION_QUESTIONS_POSTGRES !== '1' }, async () => {
  dotenv.config({ quiet: true });
  const host = process.env.DB_HOST || 'localhost';
  assert.ok(['localhost', '127.0.0.1', '::1'].includes(host), 'This test only uses local PostgreSQL.');
  const client = new Client({ host, port: Number(process.env.DB_PORT || 5432), database: process.env.DB_NAME || 'maz_winter_school', user: process.env.DB_USER || 'postgres', password: process.env.DB_PASSWORD || '', connectionTimeoutMillis: 2000 });
  await client.connect();
  try {
    // All tables are session-local, including tables created by ensureSchema.
    await client.query(`CREATE TEMP TABLE users (id VARCHAR(50) PRIMARY KEY, first_name TEXT, last_name TEXT, organization TEXT);
      CREATE TEMP TABLE speakers (id VARCHAR(50) PRIMARY KEY);
      CREATE TEMP TABLE sessions (id VARCHAR(50) PRIMARY KEY);
      SET search_path TO pg_temp;
      INSERT INTO users VALUES ('user_1','Test','Speaker','Sample Company'),('user_2','Other','Attendee','Other Company');
      INSERT INTO speakers VALUES ('speaker_1'),('speaker_2');
      INSERT INTO sessions VALUES ('session_1'),('session_2');`);
    const pool = { query: client.query.bind(client), connect: async () => ({ query: client.query.bind(client), release() {} }) } as unknown as Pool;
    const store = new SessionQuestionStore(pool);
    await store.ensureSchema();
    await store.ensureSchema();
    assert.equal((await client.query("SELECT relpersistence FROM pg_class WHERE oid = 'audience_questions'::regclass")).rows[0].relpersistence, 't');
    await store.assign('speaker_1', 'user_1', ['session_1', 'session_2']);
    assert.deepEqual((await store.presenterSessionIds('user_1')).sort(), ['session_1', 'session_2']);
    await assert.rejects(store.assign('speaker_2', 'user_1', ['session_1']), /duplicate key/);
    assert.deepEqual((await store.presenterSessionIds('user_1')).sort(), ['session_1', 'session_2']);
    await store.assign('speaker_2', 'user_2', ['session_1']);
    assert.deepEqual(await store.presenterSessionIds('user_2'), ['session_1']);
    assert.equal((await store.assignments()).length, 2);
    assert.equal((await store.assignments()).find(item => item.speakerId === 'speaker_1')?.configured, true);
    const anonymous = (await store.submit('session_1', 'user_1', 'How can we apply this approach in practice?', true))!;
    const named = (await store.submit('session_1', 'user_1', 'What would be the next step for a small company?', false))!;
    const other = (await store.submit('session_1', 'user_2', 'Is there an example of this approach working?', false))!;
    assert.deepEqual([anonymous.number, named.number, other.number], [1, 2, 3]);
    assert.equal(anonymous.authorName, null);
    assert.equal(anonymous.authorCompany, null);
    assert.equal(named.authorName, 'Test Speaker');
    assert.equal(named.authorCompany, 'Sample Company');
    assert.equal('author_id' in anonymous, false);
    assert.equal((await store.list('session_1', 'presenter', 'user_1')).length, 3);
    assert.equal((await store.list('session_1', 'presenter', 'user_1'))[0].status, 'approved');
    const speakerQueue = await store.list('session_1', 'presenter', 'user_1');
    assert.equal(speakerQueue.find(question => question.id === anonymous.id)?.authorCompany, null);
    assert.equal(speakerQueue.find(question => question.id === named.id)?.authorCompany, 'Sample Company');
    assert.deepEqual((await store.list('session_1', 'display', 'user_1')).map(question => question.number), [1, 2, 3], 'All arrivals are projected without approval or individual selection');
    assert.equal((await store.list('session_1', 'own', 'user_1')).length, 2);
    assert.equal(await store.moderate('session_2', anonymous.id, 'approve'), false);
    assert.equal(await store.moderate('session_1', anonymous.id, 'display'), true);
    assert.equal(await store.moderate('session_1', named.id, 'display'), true);
    const display = await store.list('session_1', 'display', 'user_1');
    assert.deepEqual(display.map(question => question.id), [anonymous.id, named.id, other.id]);
    assert.equal(display[0].authorCompany, null);
    assert.equal(display[1].authorCompany, 'Sample Company');
    assert.equal(display[1].number, 2);
    await assert.rejects(client.query('UPDATE audience_questions SET is_displayed = TRUE WHERE id = $1', [anonymous.id]), /duplicate key/);
    assert.equal(await store.moderate('session_1', named.id, 'answer'), true);
    assert.equal((await store.list('session_1', 'display', 'user_1')).length, 3, 'Answered questions stay in the projected list');
    assert.equal(await store.moderate('session_1', anonymous.id, 'display'), true);
    assert.equal(await store.moderate('session_1', anonymous.id, 'hide'), true);
    assert.deepEqual((await store.list('session_1', 'display', 'user_1')).map(question => question.id), [named.id, other.id], 'Hiding removes only the selected question');
    assert.equal(await store.moderate('session_1', anonymous.id, 'approve'), true);
    assert.equal((await store.list('session_1', 'display', 'user_1')).length, 3, 'Restoring returns a question to the live list');
    await store.moderate('session_1', anonymous.id, 'hide');
    assert.deepEqual((await store.list('session_1', 'presenter', 'user_1')).map(question => question.id), [named.id, other.id]);
    assert.deepEqual((await store.list('session_1', 'presenter', 'user_1')).map(question => question.number), [2, 3], 'Hiding an earlier question must not renumber later ones');
    assert.equal((await store.list('session_1', 'admin', 'user_1')).length, 3);
    assert.equal(other.status, 'approved');
    for (let index = 0; index < 3; index++) assert.equal((await store.submit('session_2', 'user_1', `A further question number ${index} for this session.`, false))?.number, index + 1);
    assert.equal(await store.submit('session_2', 'user_1', 'A sixth question within the same minute.', false), null);
    await store.assign('speaker_1', null, []);
    assert.equal((await store.assignments()).find(item => item.speakerId === 'speaker_1')?.configured, true, 'An intentionally cleared assignment must not be repopulated');
    assert.deepEqual(await store.presenterSessionIds('user_1'), []);
    assert.deepEqual(await store.presenterSessionIds('user_2'), ['session_1']);
    await client.query(`INSERT INTO audience_questions (id,session_id,question_text,status) VALUES ('legacy_question','session_2','A question submitted before numbering was added.','pending')`);
    await store.ensureSchema();
    const legacy = (await store.list('session_2', 'admin', 'user_1')).find(question => question.id === 'legacy_question');
    assert.equal(legacy?.number, 4, 'Previously submitted questions receive numbers on upgrade');
    assert.equal((await store.list('session_2', 'display', 'user_1')).find(question => question.id === 'legacy_question')?.number, 4, 'Existing pending questions also appear without approval');
    assert.equal(await store.moderate('session_2', 'legacy_question', 'answer'), true);
  } finally { await client.end(); }
});
